#pragma once

#include <stdint.h>

/** Tri-state expression values. */
enum class TriState : uint8_t {
	/** Off or false value */
	Off = 0x00,
	/** On or true value */
	On = 0x01,
	/** State is unknown */
	Unknown = 0x02,
};
